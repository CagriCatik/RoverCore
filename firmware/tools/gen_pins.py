#!/usr/bin/env python3
"""Generate firmware/bsp/esp32s3/rovercore_pins.h from hardware/interfaces/pinmap.csv (single source of truth).

Usage: python3 firmware/tools/gen_pins.py [--check]
Every pinmap row of U501 with a firmware_signal and an mcu_port 'GPIOn' becomes '#define PIN_xxx n'.
--check: exit 1 if the header in the repository differs from what the pinmap gives (used by the host tests).
"""
import csv
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
CSV = ROOT / "hardware/interfaces/pinmap.csv"
OUT = ROOT / "firmware/bsp/esp32s3/rovercore_pins.h"


def render():
    rows = []
    for r in csv.DictReader(open(CSV)):
        m = re.fullmatch(r"GPIO(\d+)", r["mcu_port"].strip())
        if r["reference"] == "U501" and r["firmware_signal"].strip() and m:
            rows.append((r["firmware_signal"].strip(), int(m.group(1)), r["schematic_net"], r["direction"],
                         r["verification"]))
    names = [n for n, *_ in rows]
    gpios = [g for _, g, *_ in rows]
    if len(set(names)) != len(names) or len(set(gpios)) != len(gpios):
        raise SystemExit("pinmap: duplicate firmware signal or GPIO")
    out = ["/* GENERATED by firmware/tools/gen_pins.py from hardware/interfaces/pinmap.csv - do not edit. */",
           "#ifndef ROVERCORE_PINS_H", "#define ROVERCORE_PINS_H", ""]
    for n, g, net, d, v in sorted(rows, key=lambda r: r[1]):
        out.append("#define %-20s %2d  /* %-20s %-9s pinmap: %s */" % (n, g, net, d, v))
    out += ["", "#define ROVERCORE_PIN_COUNT %d" % len(rows), "", "#endif", ""]
    return "\n".join(out)


def main():
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("pins header %s" % ("matches pinmap.csv" if ok else "DIFFERS from pinmap.csv - run gen_pins.py"))
        sys.exit(0 if ok else 1)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print("written", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
